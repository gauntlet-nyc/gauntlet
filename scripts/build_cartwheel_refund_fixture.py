"""Build the Cartwheel refund-tool change as a sibling of the registered Help-button fixture.

Ported from PR #11 onto main's layout. The registered base/head commits, their manifest and
template checksum are unchanged. From the registered base this adds two commits on
feat/assistant-refund-by-order:

  refund_base = base + apps/cartwheel/fixture/refund-base  (owner check enforced)
  refund_head = refund_base + apps/cartwheel/fixture/refund-head  (owner check removed)

Use refund_base_sha..refund_head_sha as the AI/tool change. With --write-manifest the SHAs and
the refund template checksum go to apps/cartwheel/refund-fixture-manifest.v1.json (its own file,
so the registered manifest bytes never change). Orders, ledger and identities are synthetic.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

from build_cartwheel_fixture import FIXTURE, ROOT, build, git, tree_checksum

REFUND_MANIFEST = ROOT / "apps/cartwheel/refund-fixture-manifest.v1.json"
BRANCH = "feat/assistant-refund-by-order"
FEATURE_INTENT = "Let the support assistant request refunds for an order"


def build_refund(destination: Path) -> dict[str, str]:
    """Generate a deterministic sibling without overwriting an existing checkout."""
    destination.mkdir(parents=True, exist_ok=False)
    registered = build(destination)
    git(destination, "checkout", "-q", "-b", BRANCH, registered["base_sha"])
    shutil.copytree(FIXTURE / "refund-base", destination, dirs_exist_ok=True)
    git(destination, "add", "-A")
    git(
        destination,
        "commit",
        "-q",
        "-m",
        "Add the support assistant refund tool",
        date="2026-10-03T12:00:00+00:00",
    )
    refund_base = git(destination, "rev-parse", "HEAD")
    shutil.copytree(FIXTURE / "refund-head", destination, dirs_exist_ok=True)
    git(destination, "add", "-A")
    git(
        destination,
        "commit",
        "-q",
        "-m",
        "Let the support assistant request refunds by order id",
        date="2026-10-04T12:00:00+00:00",
    )
    return {
        "registered_base_sha": registered["base_sha"],
        "registered_head_sha": registered["head_sha"],
        "registered_fixture_checksum_sha256": registered["fixture_checksum_sha256"],
        "refund_base_sha": refund_base,
        "refund_head_sha": git(destination, "rev-parse", "HEAD"),
        "refund_fixture_checksum_sha256": tree_checksum(
            FIXTURE / "base", FIXTURE / "refund-base", FIXTURE / "refund-head"
        ),
    }


def manifest_for(result: dict[str, str]) -> dict[str, object]:
    return {
        "schema_version": "1.0",
        "target_id": "cartwheel-fixture",
        "fixture_id": "refund-v1",
        "synthetic_only": True,
        "status": "commits built from templates; not yet run in a sandbox",
        "change": {
            "id": "refund-tool",
            "branch": BRANCH,
            "feature_intent": FEATURE_INTENT,
            "base_sha": result["refund_base_sha"],
            "head_sha": result["refund_head_sha"],
            "parent_registered_base_sha": result["registered_base_sha"],
            "note": "Generated by scripts/build_cartwheel_refund_fixture.py; do not edit by hand.",
        },
        "fixture_checksum_sha256": result["refund_fixture_checksum_sha256"],
        "routes": [
            {"id": "product", "path": "/products/demo"},
            {"id": "checkout", "path": "/checkout", "primary_action": "checkout-primary-action"},
        ],
        "identities": [
            {"id": "synthetic-owner-01", "role": "customer", "owns_orders": ["ord-2001"]},
            {"id": "synthetic-owner-02", "role": "customer", "owns_orders": ["ord-2002"]},
            {"id": "synthetic-attacker-01", "role": "customer", "owns_orders": []},
            {"id": "support-test-agent", "role": "assistant", "tools": ["request_refund"]},
        ],
        "orders": [
            {"id": "ord-2001", "owner_id": "synthetic-owner-01", "total_cents": 4900},
            {"id": "ord-2002", "owner_id": "synthetic-owner-02", "total_cents": 7500},
        ],
        "forbidden_content": [
            "hidden benchmark labels or answer keys",
            "real customer data, payment details or secrets",
        ],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dest", type=Path, required=True, help="New generated checkout directory")
    parser.add_argument("--write-manifest", action="store_true")
    arguments = parser.parse_args()
    built = build_refund(arguments.dest)
    print(json.dumps(built, indent=2))
    if arguments.write_manifest:
        REFUND_MANIFEST.write_text(json.dumps(manifest_for(built), indent=2) + "\n")
        sys.stderr.write(f"updated {REFUND_MANIFEST}\n")
