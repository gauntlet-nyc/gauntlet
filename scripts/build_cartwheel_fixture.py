"""Build the Cartwheel fixture repo with deterministic base and head commits.

base = apps/cartwheel/fixture/base; head = base overlaid with apps/cartwheel/fixture/head.
Fixed author, dates and file modes make the SHAs reproducible for the same templates and git.
With --write-manifest the SHAs and checksum are recorded in fixture-manifest.v1.json.
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "apps/cartwheel/fixture"
MANIFEST = ROOT / "apps/cartwheel/fixture-manifest.v1.json"
ENV = {
    "GIT_AUTHOR_NAME": "Cartwheel Fixture",
    "GIT_AUTHOR_EMAIL": "fixture@example.invalid",
    "GIT_COMMITTER_NAME": "Cartwheel Fixture",
    "GIT_COMMITTER_EMAIL": "fixture@example.invalid",
    "GIT_CONFIG_GLOBAL": os.devnull,
    "GIT_CONFIG_SYSTEM": os.devnull,
}


def tree_checksum(*dirs: Path) -> str:
    """sha256 over relative paths and contents of the template dirs, in sorted order."""
    digest = hashlib.sha256()
    for base in dirs:
        for path in sorted(p for p in base.rglob("*") if p.is_file()):
            digest.update(f"{base.name}/{path.relative_to(base).as_posix()}\0".encode())
            digest.update(path.read_bytes())
    return digest.hexdigest()


def git(repo: Path, *args: str, date: str | None = None) -> str:
    env = {**os.environ, **ENV}
    if date:
        env["GIT_AUTHOR_DATE"] = env["GIT_COMMITTER_DATE"] = date
    out = subprocess.run(
        ["git", *args], cwd=repo, env=env, check=True, capture_output=True, text=True
    )
    return out.stdout.strip()


def build(dest: Path) -> dict[str, str]:
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(FIXTURE / "base", dest)
    git(dest, "init", "-q", "-b", "main")
    git(dest, "add", "-A")
    git(
        dest, "commit", "-q", "-m", "Initial Cartwheel storefront", date="2026-10-01T12:00:00+00:00"
    )
    base_sha = git(dest, "rev-parse", "HEAD")
    git(dest, "checkout", "-q", "-b", "feat/floating-help")
    shutil.copytree(FIXTURE / "head", dest, dirs_exist_ok=True)
    git(dest, "add", "-A")
    git(dest, "commit", "-q", "-m", "Add a floating Help button", date="2026-10-02T12:00:00+00:00")
    return {
        "base_sha": base_sha,
        "head_sha": git(dest, "rev-parse", "HEAD"),
        "fixture_checksum_sha256": tree_checksum(FIXTURE / "base", FIXTURE / "head"),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--dest", type=Path, default=ROOT / "artifacts/cartwheel-fixture")
    parser.add_argument("--write-manifest", action="store_true")
    args = parser.parse_args()
    result = build(args.dest)
    print(json.dumps(result, indent=2))
    if args.write_manifest:
        manifest = json.loads(MANIFEST.read_text())
        manifest["git_refs"] = {
            "base_sha": result["base_sha"],
            "head_sha": result["head_sha"],
            "note": "Generated by scripts/build_cartwheel_fixture.py; do not edit by hand.",
        }
        manifest["fixture_checksum_sha256"] = result["fixture_checksum_sha256"]
        manifest["status"] = "base/head commits built from templates; app not yet run in a sandbox"
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
        sys.stderr.write(f"updated {MANIFEST}\n")
